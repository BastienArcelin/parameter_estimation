def processing(network, data_dir,root,test_sample,bands,r_band,im_size,batch_size, psf, pix_scale):
    """
    Returns 

    Paramters:
    ---------
    network: network to test
    generator: generator of input images (input of network and target) and parameters for processing results (SNR, scale radius)
    bands: band-pass filters used for this VAE
    r_band: R band-pass filter number in the bands list.
    im_size= size of the stamp for the creation of images
    N: number of batch to test
    batch_size: size of the batches generated by generator
    """
    
    #psf_image = psf.drawImage(nx=im_size, ny=im_size, scale=pix_scale)

    ellipticities = []
    ellipticities_regauss = []
    e_obs = []
    e = []
    indices = []

    flux_in = []
    flux_out= []

    dfs = []
    dfs.append(pd.read_csv(os.path.join(data_dir, root+'_data_2.csv')))
    df = dfs[0]
    #df = pd.DataFrame()
    noiseless_root = data_dir+root+'_sample_2.npy'

    input_sample_len = len(np.load(test_sample, mmap_mode = 'c'))

    for j in trange(int(input_sample_len/batch_size)):
        print(j)
        psf_images = psf[j*batch_size:(j+1)*batch_size]

        input_images = np.load(test_sample, mmap_mode = 'c')
        input_to_deblend = np.tanh(np.arcsinh(input_images[j*batch_size:(j+1)*batch_size]))
        input_noiseless = np.load(str(noiseless_root), mmap_mode ='c')
        input_target = input_noiseless[j*batch_size:(j+1)*batch_size]

        for k in range (1):
            if k == 1: 
                input_target = np.flip(input_target, axis=2)
                input_to_deblend = np.flip(input_to_deblend, axis=2)
                psf_images = np.flip(psf_images, axis=2)
            elif k == 2 : 
                input_target = np.swapaxes(input_target, 2, 1)
                input_to_deblend = np.swapaxes(input_to_deblend, 2, 1)
                psf_images = np.swapaxes(psf_images, 2, 1)
            elif k == 3:
                input_target = np.swapaxes(np.flip(input_target, axis=2), 2, 1)
                input_to_deblend = np.swapaxes(np.flip(input_to_deblend, axis=2), 2, 1)
                psf_images = np.swapaxes(np.flip(psf_images, axis=2), 2, 1)

            output_vae = np.sinh(np.arctanh(network.predict([input_to_deblend,psf_images])))
            #print(output_vae.shape)
            for i in range (len(output_vae)):
                psf_img = galsim.Image(psf_images[i,:,:,r_band], copy=True)
                psf_image = galsim.InterpolatedImage(psf_img,scale = pix_scale)
                psf_image = psf_image.drawImage(nx=im_size, ny=im_size, scale=pix_scale)
                #print(i)
                try: 
                    gal_image = galsim.Image(input_target[i,:,:,r_band])
                    gal_image.scale = pix_scale

                    shear_est = 'KSB'
                    res_in = galsim.hsm.EstimateShear(gal_image, psf_image, shear_est=shear_est, strict=True)
                    #print(res_in)
                    e_in = [res_in.corrected_g1, res_in.corrected_g2]
                    e_in_obs = [res_in.observed_shape.e]

                    shear_est = 'REGAUSS'
                    res_in = galsim.hsm.EstimateShear(gal_image, psf_image, shear_est=shear_est, strict=True)
                    e_in_reg = [res_in.corrected_e1, res_in.corrected_e2]
                        

                    gal_image_out = galsim.Image(output_vae[i,:,:,r_band])
                    gal_image_out.scale = pix_scale

                    shear_est = 'KSB'
                    res_out = galsim.hsm.EstimateShear(gal_image_out, psf_image, shear_est=shear_est, strict=True)
                    #print(res_out)
                    e_out = [res_out.corrected_g1, res_out.corrected_g2]
                    e_out_obs = [res_out.observed_shape.e]

                    shear_est = 'REGAUSS'
                    res_out = galsim.hsm.EstimateShear(gal_image_out, psf_image, shear_est=shear_est, strict=True)
                    e_out_reg = [res_out.corrected_e1, res_out.corrected_e2]


                except :
                        print('error for galaxy '+str(j*400+k*100+i))
                        e_in = [np.nan, np.nan]
                        e_out = [np.nan, np.nan]
                
                        #e_obs.append([np.nan,np.nan])
                        #ellipticities.append([np.nan, np.nan])
                        #ellipticities_regauss.append([np.nan, np.nan])
                e_obs.append([e_in_obs,e_out_obs])
                ellipticities.append([e_in, e_out])
                ellipticities_regauss.append([e_in_reg, e_out_reg])
                   
                # Measurement of fluxes
                flux_in.append(np.sum(input_target[i][:,:,r_band]))
                flux_out.append(np.sum(output_vae[i][:,:,r_band]))
                #print(np.array(ellipticities).shape)
        
    print(np.array(ellipticities).shape)
    ellipticities = np.array(ellipticities)
    df['e1_in_ksb'] = ellipticities[:,0,0]
    df['e1_out_ksb'] = ellipticities[:,1,0]
    df['e1_error_ksb'] = df['e1_out_ksb'] - df['e1_in_ksb']

    df['e2_in_ksb'] = ellipticities[:,0,1]
    df['e2_out_ksb'] = ellipticities[:,1,1]
    df['e2_error_ksb'] = df['e2_out_ksb'] - df['e2_in_ksb']

    df['e_in_ksb'] = np.sqrt(df['e1_in_ksb']**2+df['e2_in_ksb']**2)
    df['e_out_ksb'] = np.sqrt(df['e1_out_ksb']**2+df['e2_out_ksb']**2)
    df['e_error_ksb'] = df['e_out_ksb'] - df['e_in_ksb']

    ellipticities_regauss = np.array(ellipticities_regauss)
    df['e1_in_reg'] = ellipticities_regauss[:,0,0]
    df['e1_out_reg'] = ellipticities_regauss[:,1,0]
    df['e1_error_reg'] = df['e1_out_reg'] - df['e1_in_reg']

    df['e2_in_reg'] = ellipticities_regauss[:,0,1]
    df['e2_out_reg'] = ellipticities_regauss[:,1,1]
    df['e2_error_reg'] = df['e2_out_reg'] - df['e2_in_reg']

    df['e_in_reg'] = np.sqrt(df['e1_in_reg']**2+df['e2_in_reg']**2)
    df['e_out_reg'] = np.sqrt(df['e1_out_reg']**2+df['e2_out_reg']**2)
    df['e_error_reg'] = df['e_out_reg'] - df['e_in_reg']

    e_obs = np.array(e_obs)
    df['e_in_obs_ksb'] = e_obs[:,0]
    df['e_out_obs_ksb'] = e_obs[:,1]
    df['e_obs_error_ksb'] = df['e_out_obs_ksb'] - df['e_in_obs_ksb']

    df['mag_in'] = -2.5*np.log10(flux_in)+27.013081134207074
    df['mag_out']= -2.5*np.log10(flux_out)+27.013081134207074
    df['delta_mag'] = df['mag_out'] - df['mag_in']

    return df


